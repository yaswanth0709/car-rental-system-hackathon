export const money = (value) => `₹${Number(Math.round(Number(value) || 0)).toLocaleString('en-IN')}`;

export const todayISO = () => new Date().toLocaleDateString('en-CA');

export const addDays = (iso, n) => {
  const base = iso ? new Date(`${iso}T00:00:00`) : new Date();
  base.setDate(base.getDate() + n);
  return base.toLocaleDateString('en-CA');
};

export const diffDays = (start, end) =>
  start && end && new Date(`${end}T00:00:00`) > new Date(`${start}T00:00:00`)
    ? Math.ceil((new Date(`${end}T00:00:00`) - new Date(`${start}T00:00:00`)) / 86400000)
    : 0;

export const formatDate = (iso) =>
  iso
    ? new Date(`${iso}T00:00:00`).toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' })
    : '—';

export const findPromo = (code) => {
  const key = String(code || '').trim().toUpperCase();
  return key && promoCodes[key] ? { code: key, ...promoCodes[key] } : null;
};

export function buildQuote({ price = 0, days = 0, extraIds = [], promo = '' }) {
  const gross = Math.max(0, days) * price;
  const longStay = days >= 7 ? Math.round(gross * 0.15) : 0;
  const selectedExtras = extraIds
    .map((id) => extras.find((extra) => extra.id === id))
    .filter(Boolean);
  const extrasTotal = selectedExtras.reduce(
    (sum, extra) => sum + extra.price * (extra.perDay ? Math.max(days, 1) : 1),
    0
  );
  const promoDef = findPromo(promo);
  const promoDiscount = promoDef
    ? promoDef.type === 'percent'
      ? Math.round(Math.max(0, gross - longStay) * (promoDef.value / 100))
      : promoDef.value
    : 0;
  const net = Math.max(0, gross - longStay - promoDiscount) + extrasTotal;
  const taxes = Math.round(net * 0.18);
  return {
    days,
    gross,
    longStay,
    extrasTotal,
    selectedExtras,
    promoDiscount,
    promoDef,
    taxes,
    total: net + taxes,
  };
}
